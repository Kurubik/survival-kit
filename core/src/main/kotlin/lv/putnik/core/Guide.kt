    fun byId(id: String): Guide? = all.find { it.id == id }
    fun normalize(text: String): String = text.lowercase(Locale.ROOT).replace('ё', 'е')
        .replace(Regex("[^\\p{L}\\p{N} ]"), " ").replace(Regex("\\s+"), " ").trim()

    fun search(query: String): List<Guide> {
        val q = normalize(query)
        if (q.isEmpty()) return all
        val words = q.split(' ').filter { it.length > 2 && it !in setOf("как", "что", "мне", "это", "для", "или", "есть") }
        return all.map { guide ->
            val keys = guide.keywords.map(::normalize)
            val score: Int = keys.map {
                val stem = it.trimEnd('а','я','ы','и','у','ю','е','о')
                if (q.contains(it) || (stem.length >= 3 && q.split(' ').any { w -> w.startsWith(stem) })) 5 else 0
            }.sum() + words.map { word ->
                if (normalize(guide.title + " " + guide.summary).contains(word)) 2 else 0
            }.sum()
            guide to score
        }.filter { it.second > 0 }.sortedByDescending { it.second }.map { it.first }
    }
